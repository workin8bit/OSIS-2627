-- 1. Enable extension pgcrypto
create extension if not exists pgcrypto;

-- 2. Tabel Settings
create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  school_name text not null default 'SMA Negeri 3 Rembang',
  election_name text not null default 'Pemilihan Ketua & Wakil OSIS',
  academic_year text not null default '2025/2026',
  is_open boolean not null default true,
  show_results boolean not null default true,
  admin_password text not null default 'admin123',
  updated_at timestamptz not null default now()
);

insert into public.settings (id, school_name, election_name, academic_year, is_open, show_results, admin_password)
values (1, 'SMA Negeri 3 Rembang', 'Pemilihan Ketua & Wakil OSIS', '2025/2026', true, true, 'admin123')
on conflict (id) do nothing;

-- 3. Tabel Candidates (Pasangan Calon)
create table if not exists public.candidates (
  id bigint generated by default as identity primary key,
  num int not null unique,
  name text not null,
  class_name text not null default '',
  slogan text default '',
  visi text not null default '',
  misi jsonb not null default '[]'::jsonb,
  caption text default '',
  votes int not null default 0,
  created_at timestamptz not null default now()
);

-- 4. Tabel Voters (DPT Pemilih)
create table if not exists public.voters (
  id bigint generated by default as identity primary key,
  nis text not null unique,
  name text not null,
  class_name text not null default '',
  password text not null default 'siswa123',
  voted boolean not null default false,
  voted_at timestamptz,
  created_at timestamptz not null default now()
);

-- 5. Tabel Votes (Rekapitulasi Suara Anonim & Aman)
create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  candidate_num int not null references public.candidates(num) on delete cascade,
  created_at timestamptz not null default now()
);

