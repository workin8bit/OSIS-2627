-- 8. Aturan Akses (Row Level Security & Public Access)
alter table public.settings enable row level security;
alter table public.candidates enable row level security;
alter table public.voters enable row level security;
alter table public.votes enable row level security;

-- Policy untuk read/write anon client
create policy "Allow all read settings" on public.settings for select using (true);
create policy "Allow update settings" on public.settings for update using (true);

create policy "Allow all read candidates" on public.candidates for select using (true);
create policy "Allow insert candidates" on public.candidates for insert with check (true);
create policy "Allow update candidates" on public.candidates for update using (true);
create policy "Allow delete candidates" on public.candidates for delete using (true);

create policy "Allow all read voters" on public.voters for select using (true);
