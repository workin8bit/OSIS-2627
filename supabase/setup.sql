-- Trigger: slug otomatis untuk berita & updated_at aspirasi
-- ---------------------------------------------------------------------
create or replace function public.slugify(txt text)
returns text
language sql immutable
as $$
  select coalesce(nullif(left(trim(both '-' from regexp_replace(lower(coalesce(txt, '')), '[^a-z0-9]+', '-', 'g')), 80), ''), 'berita');
$$;

create or replace function public.posts_set_slug()
returns trigger
language plpgsql
as $$
declare
  base text;
  candidate text;
  n int := 2;
begin
  if new.slug is null or new.slug = '' or (tg_op = 'UPDATE' and new.slug is distinct from old.slug) then
    base := public.slugify(coalesce(nullif(new.slug, ''), new.title));
    candidate := base;
    while exists (select 1 from public.posts where slug = candidate and id is distinct from new.id) loop
      candidate := base || '-' || n;
      n := n + 1;
    end loop;
    new.slug := candidate;
  end if;
  return new;
end;
$$;

drop trigger if exists posts_slug on public.posts;
create trigger posts_slug before insert or update on public.posts
  for each row execute function public.posts_set_slug();

