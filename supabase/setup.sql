-- Kirim aspirasi. Mengembalikan kode tiket. Dibatasi 5 kiriman / 10 menit / IP.
create or replace function public.submit_aspiration(
  p_message   text,
  p_category  text default 'Umum',
  p_name      text default null,
  p_class     text default null,
  p_anonymous boolean default false
)
returns text
language plpgsql volatile security definer
set search_path = public
as $$
declare
  v_ticket text;
  v_ip     text;
  v_hash   text;
  v_msg    text := trim(coalesce(p_message, ''));
begin
  if char_length(v_msg) < 10 then
    raise exception 'Pesan aspirasi minimal 10 karakter' using errcode = '22023';
  end if;
  if char_length(v_msg) > 2000 then
    raise exception 'Pesan maksimal 2000 karakter' using errcode = '22023';
  end if;

  begin
    v_ip := split_part(coalesce(current_setting('request.headers', true)::json ->> 'x-forwarded-for', ''), ',', 1);
  exception when others then
    v_ip := '';
  end;
  v_hash := md5('osis-smaga:' || coalesce(nullif(trim(v_ip), ''), 'unknown'));

  if (select count(*) from public.aspirations
      where ip_hash = v_hash and created_at > now() - interval '10 minutes') >= 5 then
    raise exception 'Terlalu banyak kiriman. Coba lagi beberapa menit lagi.' using errcode = 'P0001';
  end if;

  loop
    v_ticket := 'ASP-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6));
    exit when not exists (select 1 from public.aspirations where ticket = v_ticket);
  end loop;

  insert into public.aspirations (ticket, name, class_name, category, message, anonymous, ip_hash)
  values (
    v_ticket,
    case when p_anonymous then null else nullif(left(trim(coalesce(p_name, '')), 100), '') end,
    case when p_anonymous then null else nullif(left(trim(coalesce(p_class, '')), 20), '') end,
    coalesce(nullif(left(trim(coalesce(p_category, '')), 50), ''), 'Umum'),
    v_msg,
    coalesce(p_anonymous, false),
    v_hash
  );
  return v_ticket;
end;
$$;

-- Lacak aspirasi berdasarkan kode tiket (tanpa identitas pengirim)
create or replace function public.track_aspiration(p_ticket text)
returns table (ticket text, category text, message text, status text, response text, created_at timestamptz, updated_at timestamptz)
language sql stable security definer
set search_path = public
as $$
  select a.ticket, a.category, a.message, a.status, a.response, a.created_at, a.updated_at
  from public.aspirations a
  where a.ticket = upper(trim(p_ticket));
$$;

-- Aspirasi yang sudah selesai ditindaklanjuti (ditampilkan di halaman publik)
create or replace function public.public_aspirations(p_limit int default 6)
returns table (ticket text, category text, message text, status text, response text, updated_at timestamptz)
language sql stable security definer
set search_path = public
as $$
  select a.ticket, a.category, a.message, a.status, a.response, a.updated_at
  from public.aspirations a
  where a.status = 'selesai' and coalesce(a.response, '') <> ''
  order by a.updated_at desc
  limit least(greatest(p_limit, 1), 20);
$$;

