-- Konten publik: semua orang boleh membaca, hanya admin yang boleh mengubah
do $$
declare t text;
begin
  foreach t in array array['settings', 'divisions', 'members', 'programs', 'events', 'gallery'] loop
    execute format('drop policy if exists "Publik dapat membaca" on public.%I', t);
    execute format('create policy "Publik dapat membaca" on public.%I for select using (true)', t);
    execute format('drop policy if exists "Admin dapat mengelola" on public.%I', t);
    execute format('create policy "Admin dapat mengelola" on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;

-- Berita: publik hanya melihat yang sudah terbit
drop policy if exists "Publik membaca berita terbit" on public.posts;
create policy "Publik membaca berita terbit" on public.posts for select using (published or public.is_admin());
drop policy if exists "Admin dapat mengelola" on public.posts;
create policy "Admin dapat mengelola" on public.posts for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Aspirasi: hanya admin yang dapat mengakses tabel secara langsung.
-- Publik mengirim & melacak lewat fungsi RPC di bawah.
drop policy if exists "Admin dapat mengelola" on public.aspirations;
create policy "Admin dapat mengelola" on public.aspirations for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Admin: sesama admin boleh melihat daftar, hanya superadmin yang boleh mengubah
drop policy if exists "Admin melihat admin" on public.admins;
create policy "Admin melihat admin" on public.admins for select to authenticated using (public.is_admin());
drop policy if exists "Superadmin mengelola admin" on public.admins;
create policy "Superadmin mengelola admin" on public.admins for all to authenticated
  using (public.is_superadmin() and user_id <> auth.uid())
  with check (public.is_superadmin());

