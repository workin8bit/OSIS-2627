create table if not exists public.settings (
  key   text primary key check (key ~ '^[a-z_]+$'),
  value jsonb
);

create table if not exists public.divisions (
  id          bigint generated by default as identity primary key,
  name        text not null,
  short       text,
  description text,
  icon        text default 'Users',
  sort_order  int default 0
);

create table if not exists public.members (
  id          bigint generated by default as identity primary key,
  name        text not null,
  position    text not null,
  class_name  text,
  division_id bigint references public.divisions (id) on delete set null,
  is_core     boolean not null default false,
  photo       text,
  instagram   text,
  quote       text,
  sort_order  int default 0
);

create table if not exists public.programs (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text,
  division_id bigint references public.divisions (id) on delete set null,
  target      text,
  start_date  date,
  end_date    date,
  status      text not null default 'rencana' check (status in ('rencana', 'berjalan', 'selesai', 'batal')),
  progress    int not null default 0 check (progress between 0 and 100)
);

create table if not exists public.posts (
  id         bigint generated by default as identity primary key,
  title      text not null,
  slug       text unique not null,
  excerpt    text,
  content    text,
  cover      text,
  category   text not null default 'Kegiatan',
  author     text,
  published  boolean not null default true,
  views      int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text,
  date        date not null,
  time        time,
  location    text,
  category    text not null default 'Umum'
);

create table if not exists public.gallery (
  id         bigint generated by default as identity primary key,
  title      text,
  image      text not null,
  album      text not null default 'Umum',
  created_at timestamptz not null default now()
);

create table if not exists public.aspirations (
  id         bigint generated by default as identity primary key,
  ticket     text unique not null,
  name       text,
  class_name text,
  category   text not null default 'Umum',
  message    text not null check (char_length(message) between 10 and 2000),
  anonymous  boolean not null default false,
  status     text not null default 'baru' check (status in ('baru', 'diproses', 'selesai', 'ditolak')),
  response   text,
  ip_hash    text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists members_division_idx on public.members (division_id);
create index if not exists programs_division_idx on public.programs (division_id);
create index if not exists posts_created_idx on public.posts (created_at desc);
create index if not exists events_date_idx on public.events (date);
create index if not exists aspirations_created_idx on public.aspirations (created_at desc);
create index if not exists aspirations_ip_idx on public.aspirations (ip_hash, created_at);

-- ---------------------------------------------------------------------
-- Trigger: slug otomatis untuk berita & updated_at aspirasi
-- ---------------------------------------------------------------------
create or replace function public.slugify(txt text)
returns text
language sql immutable
as $$
  select coalesce(nullif(left(trim(both '-' from regexp_replace(lower(coalesce(txt, '')), '[^a-z0-9]+', '-', 'g')), 80), ''), 'berita');
$$;

create or replace function public.posts_set_slug()
returns trigger
language plpgsql
as $$
declare
  base text;
  candidate text;
  n int := 2;
begin
  if new.slug is null or new.slug = '' or (tg_op = 'UPDATE' and new.slug is distinct from old.slug) then
    base := public.slugify(coalesce(nullif(new.slug, ''), new.title));
    candidate := base;
    while exists (select 1 from public.posts where slug = candidate and id is distinct from new.id) loop
      candidate := base || '-' || n;
      n := n + 1;
    end loop;
    new.slug := candidate;
  end if;
  return new;
end;
$$;

drop trigger if exists posts_slug on public.posts;
create trigger posts_slug before insert or update on public.posts
  for each row execute function public.posts_set_slug();

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists aspirations_touch on public.aspirations;
create trigger aspirations_touch before update on public.aspirations
  for each row execute function public.touch_updated_at();

